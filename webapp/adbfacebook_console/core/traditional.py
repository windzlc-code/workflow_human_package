def to_traditional(value: Any) -> str:
    text = str(value or "")
    if not text:
        return ""
    for simplified, traditional in sorted(_PHRASE_MAP.items(), key=lambda item: len(item[0]), reverse=True):
        text = text.replace(simplified, traditional)
    if _OPENCC is not None:
        try:
            text = _OPENCC.convert(text)
        except Exception:
            pass
    return text.translate(_CHAR_MAP)


def traditionalize_task_entries(entries: list[dict[str, Any]]) -> list[dict[str, Any]]:
    for entry in entries:
        if "text" in entry:
            entry["text"] = to_traditional(entry.get("text"))
    return entries
